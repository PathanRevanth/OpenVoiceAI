export type IconName = keyof typeof ICONS;

export function Icon({
  name,
  size = 16,
  className = "",
  strokeWidth = 2,
  style,
}: {
  name: IconName;
  size?: number;
  className?: string;
  strokeWidth?: number;
  style?: CSSProperties;
}) {
  const Glyph = ICONS[name];
  return <Glyph size={size} className={className} strokeWidth={strokeWidth} style={style} aria-hidden />;
}
